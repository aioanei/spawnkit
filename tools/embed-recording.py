#!/usr/bin/env python3
"""Embeds the reviewed whole-game recording in the ai module, so the builder can play it as a labelled replay (C13b).

Run from the repository root after the recording changes:

    python tools/embed-recording.py

It writes ai/src/dev/spawnkit/ai/JungleBananaRunJson.kt from ai/recordings/jungle-banana-run.json. The JVM test
WholeGameReplayTest fails while the two differ. A generated source keeps both builds (Gradle and the Kotlin Toolchain)
free of extra build logic; strings are split into short lines that stay under the 140-column lint limit.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "ai" / "recordings" / "jungle-banana-run.json"
TARGET = ROOT / "ai" / "src" / "dev" / "spawnkit" / "ai" / "JungleBananaRunJson.kt"
CHUNK = 50  # escaped, each line stays under ktlint's 140 columns


def escape(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            continue
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    lines = [
        "// Generated by tools/embed-recording.py from ai/recordings/jungle-banana-run.json. Do not edit.",
        "package dev.spawnkit.ai",
        "",
        "/** The reviewed Jungle Banana Run recording (C13a) as JSON text; read it through [WholeGameReplay]. */",
        "internal object JungleBananaRunJson {",
        "    val text: String by lazy {",
        "        buildString {",
    ]
    for start in range(0, len(text), CHUNK):
        lines.append('            append("' + escape(text[start : start + CHUNK]) + '")')
    lines += ["        }", "    }", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)} ({len(text)} characters)")


if __name__ == "__main__":
    main()
