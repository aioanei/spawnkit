import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Embeds every `<templatesDir>/<name>/project.json` into a generated Kotlin object (`EmbeddedTemplates` by default) so
 * the documents load identically on every Kotlin target (no resource APIs needed; see ADR-0003).
 */
@CacheableTask
abstract class GenerateEmbeddedTemplatesTask : DefaultTask() {
    /** Directory containing one sub-directory per template. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val templatesDir: DirectoryProperty

    /** Kotlin source root receiving the generated file. */
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    /** Package of the generated object. */
    @get:Input
    abstract val packageName: Property<String>

    /** Name of the generated object. */
    @get:Input
    abstract val objectName: Property<String>

    @TaskAction
    fun generate() {
        val templates =
            templatesDir
                .get()
                .asFile
                .listFiles()
                .orEmpty()
                .filter { it.isDirectory && File(it, "project.json").isFile }
                .sortedBy { it.name }
        val root = outputDir.get().asFile
        root.listFiles()?.forEach { it.deleteRecursively() }
        val packageDir = root.resolve(packageName.get().replace('.', '/'))
        packageDir.mkdirs()
        File(packageDir, "${objectName.get()}.kt").writeText(render(templates))
    }

    private fun render(templates: List<File>): String =
        buildString {
            appendLine("// Generated by build-logic (GenerateEmbeddedTemplatesTask). Do not edit.")
            appendLine("package ${packageName.get()}")
            appendLine()
            appendLine("/** Project documents embedded at build time. */")
            appendLine("public object ${objectName.get()} {")
            appendLine("    /** Raw JSON of every template, keyed by template directory name (e.g. `platformer-adventure`). */")
            appendLine("    public val all: Map<String, String> by lazy {")
            appendLine("        mapOf(")
            templates.forEach { appendLine("            \"${it.name}\" to ${functionName(it.name)}(),") }
            appendLine("        )")
            appendLine("    }")
            templates.forEach { dir ->
                val json = File(dir, "project.json").readText().replace("\r\n", "\n")
                appendLine()
                appendLine("    private fun ${functionName(dir.name)}(): String =")
                appendLine("        buildString {")
                json.chunked(CHUNK_SIZE).forEach { appendLine("            append(\"${escape(it)}\")") }
                appendLine("        }")
            }
            appendLine("}")
        }

    private fun functionName(directory: String): String =
        directory
            .split('-', '_', ' ')
            .filter { it.isNotEmpty() }
            .mapIndexed { index, part -> if (index == 0) part.lowercase() else part.replaceFirstChar { it.uppercase() } }
            .joinToString("")

    private fun escape(text: String): String =
        buildString {
            text.forEach { ch ->
                when (ch) {
                    '\\' -> append("\\\\")
                    '"' -> append("\\\"")
                    '$' -> append("\\$")
                    '\n' -> append("\\n")
                    '\t' -> append("\\t")
                    '\r' -> Unit
                    else -> append(ch)
                }
            }
        }

    private companion object {
        /** Keeps each string constant well below the JVM's 65 535-byte constant pool limit. */
        const val CHUNK_SIZE = 16_000
    }
}
