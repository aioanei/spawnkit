package dev.spawnkit.build.templates

/** One template directory: its name and the raw JSON of its `project.json`. */
data class EmbeddedTemplate(
    val directoryName: String,
    val json: String,
)

/** Keeps each string constant well below the JVM's 65 535-byte constant pool limit. */
private const val CHUNK_SIZE = 16_000

/** Renders the `EmbeddedTemplates` source with the same structure the former Gradle task produced. */
fun renderEmbeddedTemplates(
    packageName: String,
    templates: List<EmbeddedTemplate>,
): String =
    buildString {
        appendLine("// Generated by the embedded-templates Kotlin Toolchain plugin. Do not edit.")
        appendLine("package $packageName")
        appendLine()
        appendLine("/** Template Game Documents embedded at build time. */")
        appendLine("public object EmbeddedTemplates {")
        appendLine("    /** Raw JSON of every template, keyed by template directory name (e.g. `platformer-adventure`). */")
        appendLine("    public val all: Map<String, String> by lazy {")
        appendLine("        mapOf(")
        templates.forEach { appendLine("            \"${it.directoryName}\" to ${functionName(it.directoryName)}(),") }
        appendLine("        )")
        appendLine("    }")
        templates.forEach { template ->
            val json = template.json.replace("\r\n", "\n")
            appendLine()
            appendLine("    private fun ${functionName(template.directoryName)}(): String =")
            appendLine("        buildString {")
            json.chunked(CHUNK_SIZE).forEach { appendLine("            append(\"${escape(it)}\")") }
            appendLine("        }")
        }
        appendLine("}")
    }

private fun functionName(directory: String): String =
    directory
        .split('-', '_', ' ')
        .filter { it.isNotEmpty() }
        .mapIndexed { index, part -> if (index == 0) part.lowercase() else part.replaceFirstChar { it.uppercase() } }
        .joinToString("")

private fun escape(text: String): String =
    buildString {
        text.forEach { ch ->
            when (ch) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\t' -> append("\\t")
                '\r' -> Unit
                else -> append(ch)
            }
        }
    }
